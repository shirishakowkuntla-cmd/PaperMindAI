"""
Utility functions for PaperMind AI.
Includes export formatting, dataset loading, and report generation.
"""

from typing import Dict, List
import datetime


def generate_markdown_report(paper_data: Dict) -> str:
    """Generates a downloadable Markdown academic briefing report."""
    title = paper_data.get("title", "Untitled Research Paper")
    metadata = paper_data.get("metadata") or {}
    classification = paper_data.get("classification") or {}
    summary = paper_data.get("summary") or {}
    keywords = paper_data.get("keywords") or []

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

    kw_list = ", ".join([f"`{k['phrase']}`" for k in keywords[:10]]) if keywords else "None extracted"
    wc = metadata.get("word_count")
    wc_str = f"{wc:,} words" if isinstance(wc, (int, float)) else "N/A"

    md = f"""# PaperMind AI — Research Paper Intelligence Briefing

**Generated on:** {now_str}  
**Document Title:** {title}  

---

## 1. Document Metadata
- **Total Pages:** {metadata.get('page_count', 'N/A')}
- **Total Word Count:** {wc_str}
- **Estimated Reading Time:** ~{metadata.get('estimated_reading_time_mins', 'N/A')} minutes
- **Extraction Engine:** {metadata.get('extractor_engine', 'PyMuPDF')}

---

## 2. Research Domain Classification
- **Primary Predicted Domain:** **{classification.get('predicted_category', 'Unknown')}**
- **Classification Confidence:** {round(classification.get('confidence', 0.0) * 100, 2)}%
- **Classification Engine:** {classification.get('engine', 'Transformer')}

---

## 3. Executive Summary
{summary.get('executive_summary', 'No summary generated.')}

---

## 4. Deep-Dive Section Summaries

### 🎯 Problem Statement & Objectives
{summary.get('problem_statement', 'N/A')}

### ⚙️ Proposed Methodology & Architecture
{summary.get('methodology', 'N/A')}

### 📊 Experimental Findings & Results
{summary.get('findings', 'N/A')}

### 💡 Conclusions & Takeaways
{summary.get('conclusion', 'N/A')}

---

## 5. Extracted Technical Keywords
{kw_list}

---
*Report generated by PaperMind AI Deep Learning Analysis Pipeline.*
"""
    return md
